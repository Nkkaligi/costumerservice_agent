async def discover_tools():
    # Store original fileno methods
    original_stdout_fileno = getattr(sys.stdout, 'fileno', None)
    original_stderr_fileno = getattr(sys.stderr, 'fileno', None)

    # Open a real system null file to borrow its valid file descriptor
    with open(os.devnull, "w") as devnull:
        fd = devnull.fileno()

        # Temporarily patch fileno to return a valid descriptor instead of raising UnsupportedOperation
        sys.stdout.fileno = lambda: fd
        sys.stderr.fileno = lambda: fd

        try:
            async with Client(server_params) as mcp_client:
                tools = await mcp_client.list_tools()

                print("Available MCP tools:")
                print("=" * 50)

                for tool in tools.tools:
                    print("Tool:", tool.name)
                    print("Description:", tool.description)
                    print("-" * 50)
        finally:
            # Restore original fileno behavior
            if original_stdout_fileno:
                sys.stdout.fileno = original_stdout_fileno
            else:
                delattr(sys.stdout, 'fileno')

            if original_stderr_fileno:
                sys.stderr.fileno = original_stderr_fileno
            else:
                delattr(sys.stderr, 'fileno')

await discover_tools()

