def create_rag_context(results):

    context_parts = []

    for i, result in enumerate(
        results,
        start=1
    ):

        source = (
            f"[Source {i}: "
            f"{result['paper']}, "
            f"page {result['page']}]"
        )

        context_parts.append(
            source + "\n" + result["text"]
        )

    return "\n\n".join(context_parts)

