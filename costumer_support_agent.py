import re


def validate_citations(
    answer,
    evidence_package
):

    used = set(
        re.findall(
            r"\[(L\d+|E\d+)\]",
            answer
        )
    )

    valid = set()

    for source in evidence_package[
        "local_sources"
    ]:
        valid.add(source["id"])

    for source in evidence_package[
        "external_sources"
    ]:
        valid.add(source["id"])

    invalid = used - valid

    unused = valid - used

    return {
        "used_citations":
            sorted(used),

        "valid_citations":
            sorted(valid),

        "invalid_citations":
            sorted(invalid),

        "unused_sources":
            sorted(unused),

        "citation_valid":
            len(invalid) == 0
    }

